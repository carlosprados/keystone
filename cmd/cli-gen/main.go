// Command cli-gen writes the published command-line reference, derived from the
// definitions the binaries themselves run on.
//
// The point is the same as cmd/openapi-gen: the page cannot drift. keystonectl's
// commands, flags and examples are walked from the Cobra tree in internal/cli,
// and the agent's flags come from running its own -help. A command added without
// regenerating this page makes CI fail.
//
// The page was previously written by hand, and it showed: it shipped with the
// help output of a binary built in a scratch directory, publishing a stranger's
// temporary path as the agent's usage line.
//
// It writes two pages: the agent's flags, and keystonectl's own reference.
//
// Usage:
//
//	go run ./cmd/cli-gen -dir site/content/reference
//	go run ./cmd/cli-gen -check          # fail if either page is out of date
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/carlosprados/keystone/internal/cli"
	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

const defaultDir = "site/content/reference"

func main() {
	dir := flag.String("dir", defaultDir, "directory holding the generated reference pages")
	check := flag.Bool("check", false, "exit non-zero if the files on disk differ from what would be generated")
	flag.Parse()

	pages, err := generate()
	if err != nil {
		fmt.Fprintf(os.Stderr, "cli-gen: %v\n", err)
		os.Exit(1)
	}

	for _, name := range sortedNames(pages) {
		path := filepath.Join(*dir, name)
		body := pages[name]

		if *check {
			existing, err := os.ReadFile(path)
			if err != nil {
				fmt.Fprintf(os.Stderr, "cli-gen: cannot read %s: %v\n", path, err)
				os.Exit(1)
			}
			if !bytes.Equal(bytes.TrimSpace(existing), bytes.TrimSpace(body)) {
				fmt.Fprintf(os.Stderr, "cli-gen: %s is out of date; run `task cli-docs`\n", path)
				os.Exit(1)
			}
			fmt.Printf("cli-gen: %s is up to date\n", path)
			continue
		}

		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "cli-gen: %v\n", err)
			os.Exit(1)
		}
		if err := os.WriteFile(path, body, 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "cli-gen: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("cli-gen: wrote %s\n", path)
	}
}

func sortedNames(pages map[string][]byte) []string {
	names := make([]string, 0, len(pages))
	for name := range pages {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// generate builds one page per binary. keystonectl gets its own, so it appears
// in the site navigation rather than being buried halfway down the agent's flag
// reference.
func generate() (map[string][]byte, error) {
	agentHelp, err := agentUsage()
	if err != nil {
		return nil, err
	}

	var agent strings.Builder
	agent.WriteString(agentFrontMatter)
	agent.WriteString(generatedNotice)
	agent.WriteString(agentSection(agentHelp))
	agent.WriteString(tailSection)

	var ctl strings.Builder
	ctl.WriteString(ctlFrontMatter)
	ctl.WriteString(generatedNotice)
	ctl.WriteString(keystonectlSection())

	return map[string][]byte{
		"cli.md":         []byte(agent.String()),
		"keystonectl.md": []byte(ctl.String()),
	}, nil
}

const agentFrontMatter = `+++
title = "Agent flags"
weight = 71
description = "Every flag the keystone agent accepts."
+++

`

const ctlFrontMatter = `+++
title = "keystonectl"
weight = 72
description = "The command-line client: every command, its flags, and how to reach an agent over SSH."
+++

`

const generatedNotice = `<!-- Generated by cmd/cli-gen from the agent's flag set and keystonectl's command
     tree. Do not edit by hand: run ` + "`task cli-docs`" + ` after changing either. -->

`

// agentUsage builds the agent and reads its own -help output, so the documented
// flags are the ones the binary actually accepts.
func agentUsage() (string, error) {
	dir, err := os.MkdirTemp("", "cli-gen")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(dir)

	bin := filepath.Join(dir, "keystone")
	build := exec.Command("go", "build", "-o", bin, "./cmd/keystone")
	if out, err := build.CombinedOutput(); err != nil {
		return "", fmt.Errorf("building the agent: %w\n%s", err, out)
	}

	// -help exits non-zero by convention in the flag package; the output is
	// what matters.
	help, _ := exec.Command(bin, "-help").CombinedOutput()

	// The usage line names the binary by path, which would publish whatever
	// temporary directory this ran in.
	usage := regexp.MustCompile(`(?m)^Usage of .*:$`)
	return usage.ReplaceAllString(strings.TrimSpace(string(help)), "Usage of keystone:"), nil
}

func agentSection(help string) string {
	return "The authoritative list is always `keystone --help` on the binary you are\nrunning. This is that output:\n\n```text\n" +
		help + "\n```\n\n" + agentProse
}

