// keystonectlSection walks the real command tree, so a new command appears here
// the moment it is added.
func keystonectlSection() string {
	root := cli.NewRootCommand()

	var b strings.Builder
	b.WriteString(ctlIntro)

	b.WriteString("### The commands\n\n")
	for _, group := range root.Groups() {
		var rows []string
		for _, cmd := range root.Commands() {
			if cmd.GroupID != group.ID || !cmd.IsAvailableCommand() {
				continue
			}
			rows = append(rows, fmt.Sprintf("| `%s` | %s |\n", cmd.Use, cmd.Short))
		}
		if len(rows) == 0 {
			continue
		}
		b.WriteString("**" + strings.TrimSuffix(group.Title, ":") + "**\n\n")
		b.WriteString("| Command | What it does |\n|---|---|\n")
		for _, row := range rows {
			b.WriteString(row)
		}
		b.WriteString("\n")
	}

	b.WriteString(ctlFlags(root))
	b.WriteString(ctlOutro)
	return b.String()
}

